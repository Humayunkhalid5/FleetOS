/** Category for cover purposes: the stored one, else a guess from the name. */
function coverCategory(businessCategory, name = '') {
  if (PHOTOS[businessCategory] && businessCategory !== 'other') return businessCategory;
  const hint = NAME_HINTS.find(([pattern]) => pattern.test(name));
  return hint ? hint[1] : businessCategory || 'field-services';
}

/** Stable cover address for a company: same company, same photo. */
function coverImageFor(businessCategory, seed = '', name = '') {
  const list = PHOTOS[coverCategory(businessCategory, name)] || PHOTOS['field-services'];
  const index = crypto.createHash('sha1').update(String(seed)).digest()[0] % list.length;
  return photoUrl(list[index]);
}

